export function getSubjectsForSelection(selectedClass: string, selectedGroup: string): SubjectData[] {
  const cls = BASE_CATALOG[selectedClass] ? selectedClass : 'HSC';
  const grp = BASE_CATALOG[cls][selectedGroup] ? selectedGroup : 'Business Studies';
  const baseList = BASE_CATALOG[cls][grp] || HSC_BUSINESS_SUBJECTS;
  const customMap = storeState?.customSubjectsMap?.[`${cls}__${grp}`] || {};
  const merged = baseList.map((baseSubj) => customMap[baseSubj.id] || baseSubj);
  Object.keys(customMap).forEach((k) => {
    if (!merged.some((m) => m.id === k)) merged.push(customMap[k]);
  });
  return merged;
}

export async function signInOrSignUpUser(params: {
  mode: 'signin' | 'signup';
  name: string;
  email: string;
  password: string;
}): Promise<{ id: string; name: string; email: string }> {
  const check = validateAuthenticEmail(params.email);
  if (!check.valid || !check.email) throw new Error(check.reason || 'অনুগ্রহ করে একটি সঠিক ইমেইল দিন।');
  if (!params.password || params.password.length < 6) throw new Error('পাসওয়ার্ড কমপক্ষে ৬ অক্ষরের হতে হবে।');

  if (supabase?.auth) {
    if (params.mode === 'signup') {
      const displayName = (params.name || check.email.split('@')[0]).trim();
      const { data, error } = await supabase.auth.signUp({
        email: check.email,
        password: params.password,
        options: {
          data: {
            full_name: displayName,
            username: '@' + check.email.split('@')[0].replace(/[^a-zA-Z0-9_]/g, '').slice(0, 15),
          },
        },
      });
      if (error) {
        if (error.message?.toLowerCase().includes('already registered')) {
          throw new Error('এই ইমেইলে ইতিমধ্যে অ্যাকাউন্ট রয়েছে। "সাইন ইন করুন" অপশন ব্যবহার করুন।');
        }
        throw new Error(error.message || 'অ্যাকাউন্ট তৈরি করা সম্ভব হয়নি।');
      }
      const uid = data?.user?.id || `local-${Date.now()}`;
      await upsertLiveUserProfile({
        id: uid,
        name: displayName,
        email: check.email,
        targetTrack: `${storeState.selectedClass} • ${storeState.selectedGroup}`,
        xp: storeState.xp,
        streak: storeState.streak,
        chapterMastery: storeState.chapterMastery,
      });
      return { id: uid, name: displayName, email: check.email };
    } else {
      const { data, error } = await supabase.auth.signInWithPassword({
        email: check.email,
        password: params.password,
      });
      if (error) {
        if (error.message?.toLowerCase().includes('invalid login credentials')) {
          throw new Error('ইমেইল বা পাসওয়ার্ড সঠিক নয়। নতুন ইউজার হলে নিচে "নতুন তৈরি করুন"-এ ক্লিক করুন।');
        }
        if (error.message?.toLowerCase().includes('email not confirmed')) {
          throw new Error('আপনার ইমেইলে পাঠানো কনফার্মেশন লিংকে ক্লিক করে ইমেইলটি ভেরিফাই করুন অথবা Google দিয়ে লগইন করুন।');
        }
        throw new Error(error.message || 'সাইন ইন করা সম্ভব হয়নি।');
      }
      if (data?.user) {
        const displayName =
          data.user.user_metadata?.full_name || data.user.user_metadata?.name || check.email.split('@')[0];
        await upsertLiveUserProfile({
          id: data.user.id,
          name: displayName,
          email: check.email,
          targetTrack: `${storeState.selectedClass} • ${storeState.selectedGroup}`,
          xp: storeState.xp,
          streak: storeState.streak,
          chapterMastery: storeState.chapterMastery,
        });
        return { id: data.user.id, name: displayName, email: check.email };
      }
    }
  }
  return { id: `local-${Date.now()}`, name: params.name || check.email.split('@')[0], email: check.email };
}

