let authListenerInitialized = false;

function initSupabaseAuthSync() {
  if (typeof window === 'undefined' || authListenerInitialized || !supabase?.auth) return;
  authListenerInitialized = true;

  const applySupabaseUser = async (user: any) => {
    if (!user) return;
    const meta = user.user_metadata || {};
    const displayName =
      meta.full_name ||
      meta.name ||
      (storeState.userName && storeState.userName !== 'শিক্ষার্থী' && storeState.userName !== 'শিক্ষার্থী (Scholar)'
        ? storeState.userName
        : user.email?.split('@')[0] || 'Scholar');
    const avatarUrl = meta.avatar_url || meta.picture || storeState.userAvatar || '';
    const email = user.email || storeState.userEmail || '';

    let mergedXp = storeState.xp;
    let mergedStreak = storeState.streak;
    let mergedMastery = { ...storeState.chapterMastery };

    try {
      const { data: row } = await supabase.from('user_profiles').select('*').eq('id', user.id).maybeSingle();
      if (row) {
        mergedXp = Math.max(mergedXp, Number(row.xp) || 0);
        mergedStreak = Math.max(mergedStreak, Number(row.streak_days) || 1);
        if (row.subject_mastery && typeof row.subject_mastery === 'object') {
          mergedMastery = { ...row.subject_mastery, ...mergedMastery };
        }
      }
    } catch {}

    setState({
      userId: user.id,
      userName: displayName,
      userEmail: email,
      userAvatar: avatarUrl,
      isAuthenticated: true,
      xp: mergedXp,
      streak: mergedStreak,
      chapterMastery: mergedMastery,
      isAuthModalOpen: false,
    });

    await upsertLiveUserProfile({
      id: user.id,
      name: displayName,
      email,
      avatar: avatarUrl,
      targetTrack: `${storeState.selectedClass} • ${storeState.selectedGroup}`,
      xp: mergedXp,
      streak: mergedStreak,
      chapterMastery: mergedMastery,
    });

    if (window.location.hash.includes('access_token=')) {
      try {
        window.history.replaceState(null, '', `#${storeState.activeTab}`);
      } catch {}
    }
  };

  supabase.auth.getSession().then(({ data }) => {
    if (data?.session?.user) applySupabaseUser(data.session.user);
  }).catch(() => {});

  supabase.auth.onAuthStateChange((event, session) => {
    if ((event === 'SIGNED_IN' || event === 'TOKEN_REFRESHED' || event === 'INITIAL_SESSION') && session?.user) {
      applySupabaseUser(session.user);
    } else if (event === 'SIGNED_OUT') {
      setState({
        userId: null,
        userName: 'শিক্ষার্থী',
        userEmail: '',
        userAvatar: '',
        isAuthenticated: false,
      });
    }
  });
}

initSupabaseAuthSync();

