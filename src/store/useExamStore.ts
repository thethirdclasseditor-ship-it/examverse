const STORAGE_KEY = 'examverse-v5-storage';
const listeners = new Set<() => void>();
const VALID_NAV_TABS: NavTabId[] = [
  'dashboard', 'subjects', 'leaderboard', 'Analytics', 'analytics', 'achievements',
  'formulas', 'battle', 'mistakes', 'flashcards', 'planner', 'community', 'admin',
];

function getInitialTabFromUrlOrStorage(savedTab?: NavTabId): NavTabId {
  if (typeof window !== 'undefined') {
    const rawHash = window.location.hash.replace(/^#\/?/, '').trim();
    if (
      rawHash &&
      !rawHash.startsWith('access_token=') &&
      !rawHash.startsWith('error=') &&
      VALID_NAV_TABS.includes(rawHash as NavTabId)
    ) {
      return rawHash === 'analytics' ? 'Analytics' : (rawHash as NavTabId);
    }
  }
  if (savedTab && VALID_NAV_TABS.includes(savedTab)) {
    return savedTab === 'analytics' ? 'Analytics' : savedTab;
  }
  return 'dashboard';
}

function applyThemeToDocument(isDark: boolean) {
  if (typeof document === 'undefined') return;
  const themeStr = isDark ? 'dark' : 'light';
  document.documentElement.classList.toggle('dark', isDark);
  document.documentElement.setAttribute('data-theme', themeStr);
  try {
    window.localStorage.setItem('examverse_theme', themeStr);
  } catch {}
}

function loadPersisted(): Partial<ExamStoreState> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw);
    return parsed?.state || parsed || {};
  } catch {
    return {};
  }
}

