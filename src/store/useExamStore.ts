function mutateCustomSubj(
  targetClass: string,
  targetGroup: string,
  subjectId: string,
  fallbackName: { bn: string; en: string },
  fn: (subj: SubjectData) => void
) {
  const key = `${targetClass}__${targetGroup}`;
  const existingGroupMap = { ...(storeState.customSubjectsMap[key] || {}) };
  const baseSubj = getSubjectsForSelection(targetClass, targetGroup).find((s) => s.id === subjectId);
  const targetSubj: SubjectData = existingGroupMap[subjectId]
    ? JSON.parse(JSON.stringify(existingGroupMap[subjectId]))
    : baseSubj
    ? JSON.parse(JSON.stringify(baseSubj))
    : { id: subjectId, name: fallbackName, icon: '📘', color: '#4F46E5', chapters: [] };
  fn(targetSubj);
  existingGroupMap[subjectId] = targetSubj;
  setState({ customSubjectsMap: { ...storeState.customSubjectsMap, [key]: existingGroupMap } });
}

